    /** Custom and family words never acquire an unrelated built-in image by label. */
    fun keyForSeed(categoryId: String, originalText: String, subgroup: String = ""): String? {
        if (categoryId.startsWith("custom_") || categoryId == "family") return null
        // Cuisine is country-specific. Only Libyan dishes can use the Libyan image catalogue.
        if (categoryId == RegionalDishesCatalog.CATEGORY_ID &&
            subgroup.isNotBlank() &&
            subgroup != RegionalDishesCatalog.subgroupFor(ArabicDialect.LIBYAN)) return null
        return legacyAliases[originalText.trim().replace(Regex("[\\u064B-\\u065F\\u0670]"), "")]
    }

    /** The persisted semantic key takes priority, never the translated label. */
    fun imageFor(item: WordItem): String? =
        item.semanticKey ?: keyForSeed(item.categoryId, item.displayText, item.subgroup)
}
