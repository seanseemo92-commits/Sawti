    /** Combine the historical variants with v1.6.1's explicit priority candidates. */
    internal val words: Map<String, Map<ArabicDialect, DialectForm>> by lazy {
        val newer = NeuralLexicon161.forms
        (baseWords.keys + newer.keys).associateWith { key ->
            baseWords[key].orEmpty() + newer[key].orEmpty()
        }
    }

    fun text(semanticKey: String, dialect: ArabicDialect, fallback: String): String {
        NeuralLexicon162.get(dialect, semanticKey)?.let { return it.displayText }
        val original = if (dialect == ArabicDialect.STANDARD) fallback
            else words[semanticKey]?.get(dialect)?.displayText ?: fallback
        return Audit161Confirmed.overrideLabel(dialect, semanticKey,
            DialectSpeechRevisions.overrideLabel(dialect, semanticKey, original))
    }

    fun localize(value: WordItem, dialect: ArabicDialect): WordItem {
        val item = value.forEditing()
        val key = item.semanticKey ?: return item
        if (item.categoryId.startsWith("custom_")) return item
        val regional = if (dialect == ArabicDialect.STANDARD) null
            else RegionalDishesCatalog.variant(key, dialect)
        fun custom(flag: Int) = item.customTextFields and flag != 0
        val form = DialectSpeechCatalog.resolve(item, dialect)
        val neuralSpeech = DialectSpeechCatalog.neuralTextFor(item, dialect)
        val projected = item.copy(
            displayText = form.displayText,
            ttsPrompt = form.speechText,
            phonemicCue = form.phonemicCue,
            sentencePrompt = if (custom(CardDetails.SENTENCE)) item.sentencePrompt
                else regional?.sentencePrompt ?: TransportCatalog.sentencePrompt(key, dialect) ?: item.sentencePrompt,
            sourceDetails = CardDetails.from(item),
        )
        val revised = Audit161Confirmed.reconcileSentence(item, dialect,
            DialectSpeechRevisions.applySentence(item, dialect, projected))
        val result = if (revised.copy(sourceDetails = null) == item) item.copy() else revised
        return result.also {
            it.neuralSpeechText = neuralSpeech
            it.neuralDialect = if (neuralSpeech != null) dialect else null
        }
    }
