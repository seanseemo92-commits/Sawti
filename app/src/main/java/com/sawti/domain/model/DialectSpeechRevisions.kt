        )
    }

    fun hasPatch(dialect: ArabicDialect, key: String) =
        all[dialect]?.containsKey(key) == true || hasCompletedCandidate(dialect, key)

    fun hasCompletedCandidate(dialect: ArabicDialect, key: String): Boolean =
        completed[dialect]?.containsKey(key) == true

    fun overrideLabel(dialect: ArabicDialect, key: String, text: String): String {
        val choice = all[dialect]?.get(key)?.display
        return if (choice != null && choice.expected == text) choice.proposed else text
    }

    private fun select(current: String, field: Field?, protected: Boolean): String =
        if (!protected && field != null && field.expected == current) field.proposed else current

    fun applySpeech(item: WordItem, dialect: ArabicDialect, form: SpeechForm): SpeechForm {
        if (item.categoryId.startsWith("custom_")) return form
        val key = item.semanticKey ?: return form
        // New lexical forms supersede historical exact candidates, but never user edits.
        val newest = NeuralLexicon161.forms[key]?.get(dialect)
        if (newest != null) {
            val labelCustomized = item.customTextFields and CardDetails.LABEL != 0
            val speechCustomized = item.customTextFields and CardDetails.SPEECH != 0
            val cueCustomized = item.customTextFields and CardDetails.CUE != 0
            val display = if (labelCustomized) form.displayText else newest.displayText
            val speech = if (labelCustomized || speechCustomized) form.speechText
                else requireNotNull(newest.speechText)
            val cue = if (labelCustomized || speechCustomized || cueCustomized) form.phonemicCue
                else PhonemicCue.derive(speech)
            return form.copy(displayText = display, speechText = speech, phonemicCue = cue,
                source = if (!labelCustomized && !speechCustomized) SpeechSource.EXPLICIT_DIALECT
                    else form.source)
        }
        val patch = all[dialect]?.get(key)
        val approved = completed[dialect]?.get(key)
        if (patch == null && approved == null) return form

        fun protected(flag: Int) = item.customTextFields and flag != 0
        // Keep personal labels, speech and cues untouched; apply built-in candidates
        // after legacy written patches so the supplied 245 exact values take priority.
        val revisedDisplay = if (approved != null && !protected(CardDetails.LABEL))
            approved.display else select(form.displayText, patch?.display, protected(CardDetails.LABEL))
        val revisedSpeech = if (approved != null &&
            !protected(CardDetails.SPEECH) && !protected(CardDetails.LABEL))
            approved.speech else select(form.speechText, patch?.speech,
                protected(CardDetails.SPEECH) || protected(CardDetails.LABEL))
        val revisedCue = if (approved != null &&
            !protected(CardDetails.CUE) && !protected(CardDetails.SPEECH) &&
            !protected(CardDetails.LABEL))
            PhonemicCue.derive(approved.speech)
        else if (!protected(CardDetails.CUE) && !protected(CardDetails.SPEECH) &&
            !protected(CardDetails.LABEL) && patch?.cue == null &&
            revisedSpeech != form.speechText) PhonemicCue.derive(revisedSpeech)
        else select(form.phonemicCue, patch?.cue,
            protected(CardDetails.CUE) || protected(CardDetails.SPEECH) ||
                protected(CardDetails.LABEL))
        val source = if (approved != null &&
            !protected(CardDetails.SPEECH) && !protected(CardDetails.LABEL))
            SpeechSource.EXPLICIT_DIALECT
        else if (form.source == SpeechSource.UNVOCALIZED_FALLBACK &&
            revisedSpeech != form.speechText) SpeechSource.EXPLICIT_DIALECT
        else form.source
        return form.copy(displayText = revisedDisplay, speechText = revisedSpeech,
            phonemicCue = revisedCue, source = source)
    }

    fun applySentence(original: WordItem, dialect: ArabicDialect, projected: WordItem): WordItem {
        if (original.categoryId.startsWith("custom_")) return projected
        if (original.customTextFields and CardDetails.SENTENCE != 0) return projected
        val key = original.semanticKey ?: return projected
        val patch = all[dialect]?.get(key)?.sentence ?: return projected
        val current = projected.sentencePrompt.orEmpty()
        return if (current == patch.expected) projected.copy(sentencePrompt = patch.proposed) else projected
    }
